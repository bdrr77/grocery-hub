from abc import ABC, abstractmethod

class StoreAdapter(ABC):
    name: str
    @abstractmethod
    async def health(self): ...
    @abstractmethod
    async def search_by_ean(self, ean: str): ...
    @abstractmethod
    async def search(self, query: str): ...
    @abstractmethod
    async def get_cart(self): ...
    @abstractmethod
    async def add_item(self, product_id: str, quantity: int = 1): ...
    @abstractmethod
    async def remove_item(self, product_id: str): ...
    @abstractmethod
    async def set_quantity(self, product_id: str, quantity: int): ...
    @abstractmethod
    async def clear_cart(self): ...
